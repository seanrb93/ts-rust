/// Load the animations of the game (@ 0x216840): the pack file of the animations, the two skeletons, every animation file, the properties of the animations (the ones of the
/// classes of 11 animations get the property 67, 195 or 3), and then restart the animation system.
pub fn animMake() {
    packfileLoad(0x39b578, 1, 2);
    loadSkeleton(0, 0x39b590);
    loadSkeleton(1, 0x39b5b8);
    for (name, index) in ANIMATION_FILES_1 {
        loadAnimation(name, index);
    }
    for (animation, prop) in ANIMATION_PROPS_2 {
        setAnimProp(animation, prop);
    }
    for animation in 3_i32..223 {
        let class = (animation - 3).wrapping_div(11);
        let prop = match class {
            2 | 4 | 8 | 9 | 12 | 14 | 18 | 19 => 67,
            5 | 6 | 15 | 16 => 195,
            _ => 3,
        };
        setAnimProp(animation, prop);
    }
    for animation in 223_i32..443 {
        let class = (animation - 223).wrapping_div(11);
        let prop = match class {
            2 | 4 | 8 | 9 | 12 | 14 | 18 | 19 => 67,
            5 | 6 | 15 | 16 => 195,
            _ => 3,
        };
        setAnimProp(animation, prop);
    }
    for (animation, prop) in ANIMATION_PROPS_3 {
        setAnimProp(animation, prop);
    }
    for (name, index) in ANIMATION_FILES_4 {
        loadAnimation(name, index);
    }
    for (animation, prop) in ANIMATION_PROPS_5 {
        setAnimProp(animation, prop);
    }
    for (name, index) in ANIMATION_FILES_6 {
        loadAnimation(name, index);
    }
    for (animation, prop) in ANIMATION_PROPS_7 {
        setAnimProp(animation, prop);
    }
    for (name, index) in ANIMATION_FILES_8 {
        loadAnimation(name, index);
    }
    for (animation, prop) in ANIMATION_PROPS_9 {
        setAnimProp(animation, prop);
    }
    animRestart();
}
