//! The drawing of the pieces of a breaking pane of glass.

use crate::*;

/// Draw the glass particle `particle` (the group of the pieces: its list of matrices at +928, those of the particles at +60 and +60 of that, and the last one's count at +0x1188 and
/// ucode number at +0x118c): every piece is sent as a packet of 144 bytes of three points, texture coordinates and colours (the lists of floats of the three particles read at the
/// piece's offset, 64 bytes a piece) with its own matrix (the player's matrix times the piece's); the first two pieces select the glass texture (@ 0x2a1290).
pub fn particleGlassGfx(particle: i32) {
    let frame = Frame::new(352);
    let sp = frame.sp();
    sw(sp, particle + 928);
    let first = lw(particle + 60);
    let second = lw(first + 60);
    sw(sp + 4, first + 928);
    let third = lw(second + 60);
    sw(sp + 8, second + 928);
    let last = third + 928;
    let mut piece = 0;
    if lw(last + 0x1188) <= 0 {
        return;
    }
    sw(sp + 140, first + 984);
    sw(sp + 144, second + 984);
    sw(sp + 72, third + 940);
    sw(sp + 48, first + 932);
    sw(sp + 60, first + 936);
    sw(sp + 76, first + 944);
    sw(sp + 84, first + 948);
    sw(sp + 92, first + 952);
    sw(sp + 100, first + 960);
    sw(sp + 108, first + 964);
    sw(sp + 116, first + 968);
    sw(sp + 124, first + 976);
    sw(sp + 52, second + 932);
    sw(sp + 64, second + 936);
    sw(sp + 80, second + 944);
    sw(sp + 88, second + 948);
    sw(sp + 132, first + 980);
    sw(sp + 96, second + 952);
    sw(sp + 104, second + 960);
    sw(sp + 112, second + 964);
    sw(sp + 120, second + 968);
    sw(sp + 128, second + 976);
    sw(sp + 136, second + 980);
    sw(sp + 56, third + 932);
    sw(sp + 68, third + 936);
    loop {
        sq(sp + 160, piece as u128);
        sq(sp + 176, (piece << 6) as u128);
        let matrix = memdbAlloc(64);
        let piece_matrix = lw(sp) + lq(sp + 176) as i32;
        let projection = lw(lw(g::currentplayer) + 1764);
        sceVu0MulMatrix(matrix, projection, piece_matrix);
        let packet = memdbAlloc(144);
        sb(lw(g::gfxtag) + 3, 48);
        let tag = lw(g::gfxtag);
        let number = lq(sp + 160);
        sw(tag + 4, g::vif_load_mmtx_3696e0);
        sw(g::gfxtag, tag + 16);
        sh(tag, 1);
        sb(tag + 16 + 3, 48);
        let tag = lw(g::gfxtag);
        sw(tag + 4, matrix);
        sh(tag, 4);
        sw(g::gfxtag, tag + 16);
        sb(tag + 16 + 3, 48);
        let tag = lw(g::gfxtag);
        sw(tag + 4, g::vif_entry_loadm_3696f0);
        let after = tag + 16;
        sh(tag, 1);
        sw(g::gfxtag, after);
        let offset = lq(sp + 176) as i32;
        if (number as i64) < 2_i64 {
            let picture = lw(last + 0x1180);
            let texture = lw((if -1 >= picture { 0 } else { picture }) * 40 + lw(lw(g::thistexbuf) + 4) + 32);
            sb(after + 3, 48);
            let tag = lw(g::gfxtag);
            sw(tag + 4, texture);
            sh(tag, 8);
            sw(g::gfxtag, tag + 16);
        }
        sb(lw(g::gfxtag) + 3, 48);
        let tag = lw(g::gfxtag);
        let ucode = lw(last + 0x118c) << 2;
        sw(tag + 4, packet);
        let base = lw(sp + 4);
        let list_a = lw(sp + 48);
        sw(packet, lw(ucode + g::ucode_loadgif) | 0x6c018000);
        let first_value = lwc1(base + offset);
        let mut put = packet + 4;
        let list_b = lw(sp + 60);
        let list_c = lw(sp + 76);
        let load = 0x68048000;
        sw(put, 0x8004);
        put += 4;
        let list_d = lw(sp + 84);
        let list_e = lw(sp + 92);
        sw(put, 0x302e4000);
        put += 4;
        let list_f = lw(sp + 108);
        let list_g = lw(sp + 100);
        sw(put, 1042);
        put += 4;
        let list_h = lw(sp + 116);
        sw(sp + 12, tag + 16);
        sw(put, 0);
        sh(tag, 9);
        put += 4;
        let ucode_number = lw(last + 0x118c);
        let at_a = lw(sp + 124) + offset;
        sw(g::gfxtag, lw(sp + 12));
        let at_b = lw(sp + 132) + offset;
        let at_c = lw(sp + 140) + offset;
        let at_d = lw(sp + 8) + offset;
        let at_e = lw(sp + 52) + offset;
        let list_i = lw(sp + 80);
        let at_f = lw(sp + 64) + offset;
        sw(put, lw((ucode_number << 2) + g::ucode_loadxyzw) | load);
        put += 4;
        let list_j = lw(sp + 88);
        sw(sp + 16, lw(sp + 96) + offset);
        swc1(put, first_value);
        put += 4;
        let list_k = lw(sp + 120);
        let at_g = lw(sp + 112) + offset;
        sw(sp + 20, lw(sp + 104) + offset);
        sw(sp + 24, at_g);
        let value = lwc1(list_a + offset);
        let at_h = lw(sp + 136) + offset;
        sw(sp + 28, lw(sp + 128) + offset);
        sw(sp + 32, at_h);
        swc1(put, value);
        put += 4;
        sw(sp + 36, lw(sp + 144) + offset);
        let step = number << 4;
        swc1(put, lwc1(list_b + offset));
        put += 4;
        sw(sp + 40, last + step as i32);
        piece = number as i32 + 1;
        let list_l = lw(sp + 68);
        sw(sp + 44, lw(sp + 56) + step as i32);
        let list_m = lw(sp + 72);
        swc1(put, lwc1(list_c + offset));
        put += 4;
        swc1(put, lwc1(list_d + offset));
        put += 4;
        swc1(put, lwc1(list_e + offset));
        put += 4;
        swc1(put, lwc1(list_g + offset));
        put += 4;
        swc1(put, lwc1(list_f + offset));
        put += 4;
        swc1(put, lwc1(list_h + offset));
        put += 4;
        let ucode_number = lw(last + 0x118c);
        swc1(put, lwc1(at_a));
        put += 4;
        let load_st = lw((ucode_number << 2) + g::ucode_loadst);
        swc1(put, lwc1(at_b));
        put += 4;
        swc1(put, lwc1(at_c));
        put += 4;
        let value = lwc1(at_d);
        sw(put, load_st | load);
        put += 4;
        swc1(put, value);
        put += 4;
        let ucode_now = lw(last + 0x118c) << 2;
        swc1(put, lwc1(at_e));
        put += 4;
        let load_rgba = lw(ucode_now + g::ucode_loadrgba) | 0x6e048000;
        swc1(put, lwc1(at_f));
        put += 4;
        swc1(put, lwc1(list_i + offset));
        put += 4;
        swc1(put, lwc1(list_j + offset));
        put += 4;
        swc1(put, lwc1(lw(sp + 16)));
        put += 4;
        swc1(put, lwc1(lw(sp + 20)));
        put += 4;
        swc1(put, lwc1(lw(sp + 24)));
        put += 4;
        swc1(put, lwc1(list_k + offset));
        put += 4;
        swc1(put, lwc1(lw(sp + 28)));
        put += 4;
        swc1(put, lwc1(lw(sp + 32)));
        put += 4;
        swc1(put, lwc1(lw(sp + 36)));
        put += 4;
        sw(put, load_rgba);
        put += 4;
        sw(put, lw(lw(sp + 40)));
        put += 4;
        sw(put, lw(lw(sp + 44)));
        put += 4;
        sw(put, lw(list_l + step as i32));
        sw(put + 4, lw(list_m + step as i32));
        let ucode_last = lw(last + 0x118c);
        sb(lw(sp + 12) + 3, 48);
        let tag = lw(g::gfxtag);
        let count = lw(last + 0x1188);
        sw(tag + 4, (ucode_last << 5) + g::startucode);
        sh(tag, 1);
        sw(g::gfxtag, tag + 16);
        if piece >= count {
            break;
        }
    }
}
